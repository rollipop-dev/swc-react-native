// RA3 excludes runtime globals by name, including imported/bound references.
pub(crate) fn filter_closure(
    closure: &mut Vec<swc_ecma_ast::Ident>,
    globals: &rustc_hash::FxHashSet<swc_atoms::Atom>,
) {
    closure.retain(|variable| !globals.contains(&variable.sym));
}
